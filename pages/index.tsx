import Head from 'next/head';
import styles from '@/styles/Home.module.css';

import Banner from '@/components/banner/banner';
import NavBar from '@/components/nav/navbar';
import SectionCards from '@/components/card/section-cards';

import { getPopularVideos, getVideos, getWatchAgainVideos } from '../lib/videos';
import { GetServerSideProps } from 'next';
import { verifyToken } from '@/lib/utils';
import useRedirectUser from '@/utils/redirectUser';

// Define the Video type
export interface Video {
  id: string;
  title: string;
  imgUrl: string;
}
export interface WatchAgainVideo {
  videId: string;
}

interface HomeProps {
  disneyVideos: Video[];
  travelVideos: Video[];
  productivityVideos: Video[];
  popularVideo: Video[];
  watchItAgainVideos: WatchAgainVideo[];
}

export const getServerSideProps: GetServerSideProps<HomeProps> = async (context) => {
  const { userId, token } = await useRedirectUser(context);

  const watchItAgainVideos = await getWatchAgainVideos(userId, token);
  const disneyVideos = await getVideos('Disney');
  const productivityVideos = await getVideos('Productivity');
  const travelVideos = await getVideos('travel music');
  const popularVideo = await getPopularVideos();

  return {
    props: { disneyVideos, travelVideos, productivityVideos, popularVideo, watchItAgainVideos },
  };
};

const Home: React.FC<HomeProps> = ({
  disneyVideos,
  travelVideos,
  productivityVideos,
  popularVideo,
  watchItAgainVideos = [],
}) => {
  return (
    <>
      <Head>
        <title>Nextflix</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <div className={styles.page}>
        <NavBar />
        <Banner
          videoId={'4zH5iYM4wJo'}
          title={'Clifford the red dog'}
          subTitle={'a very cute dog'}
          imgUrl="/static/clifford.webp"
        />

        <div className={styles.sectionWrapper}>
          <SectionCards title="Disney" videos={disneyVideos} size="large" />
          <SectionCards title="Watch it again" videos={watchItAgainVideos} size="medium" />
          <SectionCards title="Travel" videos={travelVideos} size="small" />
          <SectionCards title="Productivity" videos={productivityVideos} size="large" />
          <SectionCards title="Popular" videos={popularVideo} size="small" />
        </div>
      </div>
    </>
  );
};

export default Home;
